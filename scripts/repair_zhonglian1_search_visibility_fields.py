def now_iso() -> str:
    return datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds")


def parse_time(value: Any) -> float:
    text = str(value or "").strip()
    if not text or text == "unknown":
        return 0.0
    normalized = text[:-1] + "+00:00" if text.endswith("Z") else text
    try:
        return datetime.fromisoformat(normalized).timestamp()
    except ValueError:
        return 0.0


def chunks(values: Sequence[Any], size: int) -> Iterable[List[Any]]:
    for index in range(0, len(values), size):
        yield list(values[index:index + size])


def load_json(path: Path) -> Dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def save_report(suffix: str, payload: Dict[str, Any]) -> Path:
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().astimezone().strftime("%Y%m%d-%H%M%S")
    path = REPORT_DIR / f"{stamp}-{suffix}.json"
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return path


def project_relative(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def load_credentials(shop_id: str) -> Dict[str, str]:
    registry = load_json(ROOT / "ozon-adapter/shops.json")
    shop = next(
        item for item in registry.get("shops") or []
        if item.get("id") == shop_id or item.get("name") == shop_id
    )
    values: Dict[str, str] = {}
    env_path = ROOT / f"ozon-adapter/.env.{shop_id}"
    if env_path.is_file():
        for raw in env_path.read_text(encoding="utf-8").splitlines():
            line = raw.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, value = line.split("=", 1)
            values[key.strip()] = value.strip().strip('"').strip("'")
    values.update({key: value for key, value in os.environ.items() if key.startswith("OZON_")})
    return {
        "client_id": values[str(shop["client_id_env"])],
        "api_key": values[str(shop["api_key_env"])],
    }


class CountingOzonClient:
    BASE_URL = "https://api-seller.ozon.ru"
