def tag_candidates(card: Mapping[str, Any], base_intro: str, query_rows: Sequence[Mapping[str, Any]]) -> List[Dict[str, Any]]:
    candidates: List[Dict[str, Any]] = []
    for row in query_rows:
        query = safe_query(row.get("query"))
        source_kind = str(row.get("source_kind") or "search_data")
        product_level_query = source_kind in {API_QUERY_SOURCE, "ozon_search_analytics"}
        if not query:
            continue
        if not product_level_query and not query_supported(query, card, base_intro):
            continue
        tag = canonical_hashtag(query)
        if tag:
            add_unique_tag(candidates, tag, source=source_kind, phrase=query)

    title_text = str(card.get("title") or "")
    short_attributes = tag_fact_corpus(card)
    fact_texts: List[str] = [title_text, short_attributes]
    for phrase in product_specific_longtail_candidates(fact_texts):
        tag = canonical_hashtag(phrase)
        if tag:
            add_unique_tag(candidates, tag, source="product_fact", phrase=phrase)

    phrase_sources = [("title", title_text, True)]
    for source, text, include_single in phrase_sources:
        for part in re.split(r"[,.;:/()\[\]{}|*•—–-]+", text):
            part = compact_text(part)
            if not part:
                continue
            if source != "title" and len(part) > 120:
                continue
            for phrase in phrase_candidates_from_text(part, max_window=3, include_single=include_single):
                tag = canonical_hashtag(phrase)
                if tag:
                    add_unique_tag(candidates, tag, source=source, phrase=phrase)
                if len(candidates) >= 80:
                    return filter_card_candidates(candidates, card)
    for phrase in generated_selling_point_phrases(card, base_intro):
        tag = canonical_hashtag(phrase)
        if tag:
            add_unique_tag(candidates, tag, source="generated_selling_point", phrase=phrase)
        if len(candidates) >= 120:
            return filter_card_candidates(candidates, card)
    fallback_phrase_sources = [
        ("intro_short_phrase", str(base_intro or ""), False),
        ("attribute_short_phrase", short_attributes, True),
    ]
    for source, text, include_single in fallback_phrase_sources:
        for part in re.split(r"[,.;:/()\[\]{}|*•—–-]+", text):
            part = compact_text(part)
            if not part or len(part) > 120:
                continue
            for phrase in phrase_candidates_from_text(part, max_window=3, include_single=include_single):
                tag = canonical_hashtag(phrase)
                if tag:
                    add_unique_tag(candidates, tag, source=source, phrase=phrase)
                if len(candidates) >= 140:
                    return filter_card_candidates(candidates, card)
    return filter_card_candidates(candidates, card)


def select_intro_term(card: Mapping[str, Any], base_intro: str, query_rows: Sequence[Mapping[str, Any]]) -> Tuple[str, Dict[str, Any]]:
    intro_key = compact_text(base_intro).casefold()
    for row in query_rows:
        query = safe_query(row.get("query"))
        if not query:
            continue
        if query in intro_key:
            continue
        if not query_supported(query, card, base_intro):
            continue
        return query, dict(row)
    return "", {}


def build_intro(card: Mapping[str, Any], original: Optional[Mapping[str, Any]], query_rows: Sequence[Mapping[str, Any]]) -> Dict[str, Any]:
    current_intro = str(card.get("current_intro") or "").strip()
    if original:
        base = str(original.get("intro") or "").strip()
        source_status = "verified_original"
        source_report = str(original.get("source_report") or "")
        source_type = str(original.get("source_type") or "")
    else:
        base = current_intro
        source_status = "current_only_no_verified_original"
        source_report = ""
        source_type = ""
    if not base:
        return {
            "status": source_status,
            "source_report": source_report,
            "source_type": source_type,
            "base_intro": "",
            "final_intro": "",
            "supplement": "",
            "search_term": "",
            "error": "missing_intro_base",
        }
    search_term, row = select_intro_term(card, base, query_rows)
    supplement = f"По назначению это {search_term}." if search_term else ""
    final_intro = f"{base}\n\n{supplement}" if supplement else base
    return {
        "status": source_status,
        "source_report": source_report,
        "source_type": source_type,
        "base_intro": base,
        "final_intro": final_intro,
        "supplement": supplement,
        "search_term": search_term,
        "search_count": _number(row.get("count")) if row else 0,
        "search_source": row.get("source_kind") if row else "",
        "error": "" if final_intro.startswith(base) else "intro_prefix_not_preserved",
    }


def intro_moderation_risk_reason(value: Any) -> str:
    text = compact_text(value)
    if not text:
        return ""
    if "diy" in str(value).casefold():
        return "intro_contains_diy_or_foreign_marker"
    if text.casefold().startswith("важно перед покупкой"):
        return "intro_instructional_not_product_description"
    return ""


def card_update_risk_reason(card: Mapping[str, Any], final_intro: Any) -> str:
    title = str(card.get("title") or "")
    intro = str(final_intro or "")
    combined = f"{title} {intro}"
    tokens = text_tokens(combined)
    lowered = combined.casefold()
    compact = tag_key(combined)
    if has_token_prefix(tokens, "дрон", "коптер", "квадрокоптер"):
        return "prohibited_drone_risk"
    if has_token_prefix(tokens, "радиоуправляем", "радиоуправл") and has_token_prefix(tokens, "камер"):
        return "prohibited_drone_risk"
    if has_token_prefix(tokens, "урн", "прах", "мемориал") and has_token_prefix(tokens, "питом", "животн", "кошк", "собак"):
        return "prohibited_memorial_urn_risk"
    if any(
        fragment in compact
        for fragment in ("мастурбатор", "мастурбац", "интимн", "длясекса", "сексигр", "порно", "эротик", "лубрикант")
    ):
        return "adult_product_moderation_risk"
    if "soundbar" in lowered and has_token_prefix(tokens, "саундбар"):
        return "intro_brand_recheck_risk"
    return ""


def final_tag_moderation_risk_reason(final_tags: Sequence[str]) -> str:
    if any(
        (
            "коптер" in tag_key(tag)
            or "квадрокоптер" in tag_key(tag)
            or tag_key(tag).startswith(("дрон", "дроны"))
            or tag_key(tag).endswith("дрон")
        )
        for tag in final_tags
    ):
        return "prohibited_drone_risk"
    if any(
        ("урна" in tag_key(tag) or "прах" in tag_key(tag) or "мемориал" in tag_key(tag))
        and any(fragment in tag_key(tag) for fragment in ("питом", "животн", "кошк", "собак"))
        for tag in final_tags
    ):
        return "prohibited_memorial_urn_risk"
    return ""


def merge_tags(
    existing: Sequence[str],
    candidates: Sequence[Mapping[str, Any]],
    query_rows: Sequence[Mapping[str, Any]],
    card: Optional[Mapping[str, Any]] = None,
) -> Dict[str, Any]:
    existing_valid: List[str] = []
    seen: set[str] = set()
    invalid_existing: List[str] = []
    for tag in existing:
        allowed_for_card = True
        if card is not None:
            allowed_for_card = candidate_allowed_for_card({"tag": str(tag), "phrase": str(tag)}, card)
        if valid_existing_tag(tag) and allowed_for_card:
            key = tag_key(tag)
            if key and key not in seen:
                seen.add(key)
                existing_valid.append(str(tag).strip())
        else:
            invalid_existing.append(str(tag))
    if len(existing_valid) > 30:
        return {
            "final_tags": existing_valid[:30],
            "valid_existing_tags": existing_valid,
            "invalid_existing_tags": invalid_existing,
            "new_tags": [],
            "new_tag_details": [],
            "removed_tags": existing_valid[30:],
            "strategy": "over_limit_trim_blocked",
            "error": "existing_valid_tags_exceed_30",
        }

    candidate_tags: List[str] = []
    candidate_source: Dict[str, Dict[str, Any]] = {}
    existing_keys = {tag_key(tag) for tag in existing_valid}
    for item in candidates:
        tag = str(item.get("tag") or "").strip()
        key = tag_key(tag)
        if not tag or not key or key in existing_keys or key in {tag_key(value) for value in candidate_tags}:
            continue
        candidate_tags.append(tag)
        candidate_source[tag.casefold()] = dict(item)

    if len(existing_valid) < 30:
        final = list(existing_valid)
        new_tags: List[str] = []
        new_tag_details: List[Dict[str, Any]] = []
        for tag in candidate_tags:
            final.append(tag)
            new_tags.append(tag)
            new_tag_details.append({
                "tag": tag,
                "source": str((candidate_source.get(tag.casefold()) or {}).get("source") or ""),
                "phrase": str((candidate_source.get(tag.casefold()) or {}).get("phrase") or ""),
            })
            if len(final) == 30:
                break
        error = "" if len(final) == 30 else "insufficient_relevant_tag_candidates"
        return {
            "final_tags": final,
            "valid_existing_tags": existing_valid,
            "invalid_existing_tags": invalid_existing,
            "new_tags": new_tags,
            "new_tag_details": new_tag_details,
            "removed_tags": [],
            "strategy": "fill_missing",
            "error": error,
        }

    scored_existing = sorted(
        [
            (tag, _tag_search_score(tag, query_rows), index)
            for index, tag in enumerate(existing_valid)
        ],
        key=lambda item: (item[1], -item[2]),
    )
    replacements: List[Tuple[str, str]] = []
    used_existing: set[str] = set()
    for candidate in candidate_tags:
        source = candidate_source.get(candidate.casefold()) or {}
        if source.get("source") not in SEARCH_TAG_SOURCES:
            continue
        candidate_score = _tag_search_score(candidate, query_rows)
        if candidate_score <= 0:
            continue
        removable = next((
            (tag, score)
            for tag, score, _index in scored_existing
            if tag.casefold() not in used_existing and score > 0 and candidate_score > score
        ), None)
        if removable is None:
            continue
        old_tag, _old_score = removable
        replacements.append((candidate, old_tag))
        used_existing.add(old_tag.casefold())
        if len(replacements) >= 8:
            break

    final = list(existing_valid)
    for new_tag, old_tag in replacements:
        final[final.index(old_tag)] = new_tag
    return {
        "final_tags": final,
        "valid_existing_tags": existing_valid,
        "invalid_existing_tags": invalid_existing,
        "new_tags": [new for new, _old in replacements],
        "new_tag_details": [
            {
                "tag": new,
                "source": str((candidate_source.get(new.casefold()) or {}).get("source") or ""),
                "phrase": str((candidate_source.get(new.casefold()) or {}).get("phrase") or ""),
            }
            for new, _old in replacements
        ],
        "removed_tags": [old for _new, old in replacements],
        "strategy": "replace_lower_search_proven" if replacements else "keep_existing_30_no_lower_search_proof",
        "error": "",
    }


def build_cards(catalog: Sequence[Mapping[str, Any]], info_rows: Sequence[Mapping[str, Any]], attribute_rows: Sequence[Mapping[str, Any]]) -> List[Dict[str, Any]]:
    info_by_product = {
        str(item.get("id") or item.get("product_id") or ""): dict(item)
        for item in info_rows
    }
    attrs_by_offer = {
        str(item.get("offer_id") or ""): dict(item)
        for item in attribute_rows
        if str(item.get("offer_id") or "")
    }
    attrs_by_product = {
        str(item.get("id") or item.get("product_id") or ""): dict(item)
        for item in attribute_rows
    }
    cards: List[Dict[str, Any]] = []
    for item in catalog:
        product_id = str(item.get("product_id") or "").strip()
        if not product_id:
            continue
        info = info_by_product.get(product_id, {})
        offer_id = str(item.get("offer_id") or info.get("offer_id") or "").strip()
        attrs = attrs_by_offer.get(offer_id) or attrs_by_product.get(product_id) or {}
        raw_tags = attribute_value_texts(attrs, OZON_HASHTAG_ATTRIBUTE_ID)
        cards.append({
            "product_id": product_id,
            "offer_id": offer_id,
            "sku": str(info.get("sku") or item.get("sku") or ""),
            "title": str(item.get("name") or info.get("name") or info.get("title") or ""),
            "category_name": str(info.get("category_name") or info.get("category") or ""),
            "current_subject_tag_values": raw_tags,
            "current_subject_tags": split_tag_values(raw_tags),
            "current_intro": (attribute_value_texts(attrs, OZON_ANNOTATION_ATTRIBUTE_ID) or [""])[0],
            "product_attributes": attrs.get("attributes") if isinstance(attrs.get("attributes"), list) else [],
            "info": info,
            "catalog_item": dict(item),
        })
    cards.sort(key=lambda card: int(card["product_id"]) if card["product_id"].isdigit() else 0, reverse=True)
    return cards


def active_write_conflicts() -> Dict[str, Any]:
    reasons: List[str] = []
    current_path = ROOT / "logs/current-batch.json"
    if current_path.is_file():
        current = load_json(current_path)
        pid = int(_number(current.get("pid")))
        batch_id = str(current.get("batch_id") or "")
        if pid > 0:
            try:
                os.kill(pid, 0)
                alive = True
            except OSError:
                alive = False
            if alive:
                batch_path = ROOT / f"batches/{batch_id}/batch.json"
                batch = load_json(batch_path) if batch_path.is_file() else {}
                if str(batch.get("status") or "").upper() not in {"COMPLETED", "COMPLETED_WITH_ERRORS", "STOPPED", "FAILED"}:
                    reasons.append(f"active batch {batch_id} pid {pid} status {batch.get('status') or 'unknown'}")
    try:
        output = subprocess.run(
            ["ps", "-axo", "pid,command"],
            cwd=ROOT,
            check=False,
            capture_output=True,
            text=True,
            timeout=5,
        ).stdout
    except Exception:
        output = ""
    for line in output.splitlines():
        if "scripts/run_batch.py" in line and "repair_zhonglian1_search_visibility_fields.py" not in line:
            text = line.strip()
            if text and text not in reasons:
                reasons.append(text)
    return {"active": bool(reasons), "reasons": reasons}


def build_preflight(client: CountingOzonClient) -> Tuple[Dict[str, Any], Dict[str, Any]]:
    catalog = list_catalog(client)
    product_ids = sorted({int(item["product_id"]) for item in catalog if str(item.get("product_id") or "").isdigit()})
    offer_ids = [str(item.get("offer_id") or "").strip() for item in catalog if str(item.get("offer_id") or "").strip()]
    info_rows = product_info(client, product_ids)
    attribute_rows = product_attributes(client, offer_ids)
    cards = build_cards(catalog, info_rows, attribute_rows)
    date_from, date_to = search_window()
    api_query_rows_by_sku, api_query_errors = product_query_details(
        client,
        [str(card.get("sku") or "") for card in cards],
        date_from=date_from,
        date_to=date_to,
    )

    backup = {
        "schema_version": "1.0.0",
        "mode": "immutable_remote_backup",
        "shop_id": SHOP_ID,
        "generated_at": now_iso(),
        "api_query_date_from": date_from,
        "api_query_date_to": date_to,
        "catalog_card_count": len(catalog),
        "backup_card_count": len(cards),
        "catalog": catalog,
        "product_info": info_rows,
        "product_attributes": attribute_rows,
        "api_top15_search_queries_by_sku": api_query_rows_by_sku,
        "api_top15_search_query_errors": api_query_errors,
        "cards": cards,
        "write_api_calls": 0,
        "inventory_api_calls": client.inventory_api_calls,
    }
    backup_path = save_report(f"{SHOP_ID}-backup", backup)

    evidence_by_product = historical_original_evidence()
    plan = load_json(PLAN_PATH) if PLAN_PATH.is_file() else {}
    actions = {
        str(action.get("product_id") or ""): dict(action)
        for action in plan.get("actions") or []
        if isinstance(action, Mapping)
    }
    conflict = active_write_conflicts()
    items: List[Dict[str, Any]] = []
    for card in cards:
        product_id = card["product_id"]
        action = actions.get(product_id, {})
        sku = str(card.get("sku") or "").strip()
        api_query_rows = api_query_rows_by_sku.get(sku, [])
        query_rows = api_query_rows or action_query_rows(action)
        original = evidence_by_product.get(product_id)
        intro = build_intro(card, original, query_rows)
        base_intro = intro.get("base_intro") or card.get("current_intro") or ""
        candidates = tag_candidates(card, str(base_intro), query_rows)
        merged = merge_tags(card.get("current_subject_tags") or [], candidates, query_rows, card)
        final_tags = [str(tag) for tag in merged.get("final_tags") or []]
        final_intro = str(intro.get("final_intro") or "")
        new_tag_details = [dict(item) for item in merged.get("new_tag_details") or [] if isinstance(item, Mapping)]
        new_api_tags = [
            item["tag"] for item in new_tag_details
            if str(item.get("source") or "") in SEARCH_TAG_SOURCES
        ]
        generated_tags = [
            item["tag"] for item in new_tag_details
            if str(item.get("source") or "") not in SEARCH_TAG_SOURCES
        ]
        errors = [value for value in (merged.get("error"), intro.get("error")) if value]
        if len(final_tags) != 30:
            errors.append("final_subject_tag_count_not_30")
        if any(not valid_existing_tag(tag) for tag in final_tags):
            errors.append("invalid_final_subject_tag")
        if len({tag_key(tag) for tag in final_tags}) != len(final_tags):
            errors.append("duplicate_final_subject_tag")
        if not final_intro:
            errors.append("empty_final_intro")
        intro_risk = intro_moderation_risk_reason(final_intro)
        if intro_risk:
            errors.append(intro_risk)
        card_risk = card_update_risk_reason(card, final_intro)
        if card_risk:
            errors.append(card_risk)
        tag_risk = final_tag_moderation_risk_reason(final_tags)
        if tag_risk:
            errors.append(tag_risk)
        if intro.get("base_intro") and not final_intro.startswith(str(intro.get("base_intro"))):
            errors.append("original_intro_prefix_not_preserved")
        current_valid_tags = [tag for tag in card.get("current_subject_tags") or [] if valid_existing_tag(tag)]
        tag_update_required = [tag_key(tag) for tag in final_tags] != [tag_key(tag) for tag in current_valid_tags]
        intro_update_required = final_intro != str(card.get("current_intro") or "").strip()
        row_status = "ready" if not errors else "skipped"
        if row_status == "ready" and not tag_update_required and not intro_update_required:
            row_status = "already_ok"
        items.append({
            "status": row_status,
            "product_id": product_id,
            "offer_id": card.get("offer_id") or "",
            "sku": card.get("sku") or "",
            "title": card.get("title") or "",
            "current_subject_tags": card.get("current_subject_tags") or [],
            "current_valid_subject_tags": current_valid_tags,
            "current_valid_subject_tag_count": len(current_valid_tags),
            "invalid_current_subject_tags": merged.get("invalid_existing_tags") or [],
            "final_subject_tags": final_tags,
            "final_subject_tag_count": len(final_tags),
            "new_subject_tags": merged.get("new_tags") or [],
            "new_tag_details": new_tag_details,
            "new_api_subject_tags": new_api_tags,
            "generated_subject_tags": generated_tags,
            "new_api_subject_tag_count": len(new_api_tags),
            "generated_subject_tag_count": len(generated_tags),
            "removed_subject_tags": merged.get("removed_tags") or [],
            "subject_tag_strategy": merged.get("strategy") or "",
            "tag_candidates_sample": candidates[:20],
            "current_intro": str(card.get("current_intro") or ""),
            "intro_source_status": intro.get("status") or "",
            "intro_source_type": intro.get("source_type") or "",
            "intro_source_report": intro.get("source_report") or "",
            "base_intro": intro.get("base_intro") or "",
            "final_intro": final_intro,
            "final_intro_length": len(final_intro),
            "intro_supplement": intro.get("supplement") or "",
            "intro_search_term": intro.get("search_term") or "",
            "intro_search_count": intro.get("search_count") or 0,
            "intro_search_source": intro.get("search_source") or "",
            "tag_update_required": tag_update_required,
            "intro_update_required": intro_update_required,
            "requires_update": tag_update_required or intro_update_required,
            "api_top15_query_count": len(api_query_rows),
            "api_top15_queries": api_query_rows,
            "reliable_search_query_count": len(query_rows),
            "query_source_status": "api_top15" if api_query_rows else "plan_fallback" if query_rows else "none",
            "errors": errors,
        })

    ready_or_ok = [item for item in items if item["status"] in {"ready", "already_ok"}]
    preflight = {
        "schema_version": "1.0.0",
        "mode": "preflight",
        "shop_id": SHOP_ID,
        "generated_at": now_iso(),
        "api_query_date_from": date_from,
        "api_query_date_to": date_to,
        "api_top15_query_error_count": len(api_query_errors),
        "api_top15_query_errors": api_query_errors,
        "backup_report": project_relative(backup_path),
        "current_write_conflict": conflict,
        "confirmation_required_for_apply": CONFIRMATION,
        "changes": [f"attribute_{OZON_HASHTAG_ATTRIBUTE_ID}", f"attribute_{OZON_ANNOTATION_ATTRIBUTE_ID}"],
        "untouched": ["title", "price", "images", "brand", "category", "sku", "stock", "warehouse", "activation"],
        "summary": {
            "total_cards": len(items),
            "backup_cards": len(cards),
            "ready_cards": sum(item["status"] == "ready" for item in items),
            "already_ok_cards": sum(item["status"] == "already_ok" for item in items),
            "skipped_cards": sum(item["status"] == "skipped" for item in items),
            "requires_update_cards": sum(bool(item["requires_update"]) and item["status"] == "ready" for item in items),
            "verified_original_intro_cards": sum(item["intro_source_status"] == "verified_original" for item in items),
            "current_only_intro_cards": sum(item["intro_source_status"] == "current_only_no_verified_original" for item in items),
            "thirty_tag_ready_or_ok_cards": sum(item["final_subject_tag_count"] == 30 and item["status"] in {"ready", "already_ok"} for item in items),
            "api_top15_cards_with_queries": sum(item["api_top15_query_count"] > 0 for item in items),
            "new_api_subject_tag_total": sum(item["new_api_subject_tag_count"] for item in items),
            "generated_subject_tag_total": sum(item["generated_subject_tag_count"] for item in items),
            "coverage_ratio": round(len(ready_or_ok) / len(items), 4) if items else 0,
        },
        "items": items,
        "write_api_calls": 0,
        "read_api_calls": client.read_api_calls,
        "inventory_api_calls": client.inventory_api_calls,
    }
    preflight_path = save_report(f"{SHOP_ID}-preflight", preflight)
    preflight["preflight_report"] = project_relative(preflight_path)
    preflight_path.write_text(json.dumps(preflight, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return backup, preflight


def load_preflight(path_value: str) -> Tuple[Path, Dict[str, Any]]:
    path = ROOT / path_value if not Path(path_value).is_absolute() else Path(path_value)
    payload = load_json(path)
    if str(payload.get("shop_id") or "") != SHOP_ID:
        raise RuntimeError("Preflight does not belong to zhonglian1")
    return path, payload


def selected_apply_rows(preflight: Mapping[str, Any], scope: str) -> List[Dict[str, Any]]:
    rows = [
        dict(item) for item in preflight.get("items") or []
        if isinstance(item, Mapping) and item.get("status") == "ready" and item.get("requires_update")
    ]
    priority = {product_id: index for index, product_id in enumerate(PRIORITY_PRODUCTS)}
    rows.sort(key=lambda row: (
        priority.get(str(row.get("product_id") or ""), 999),
        0 if row.get("intro_source_status") == "verified_original" else 1,
        -int(row.get("reliable_search_query_count") or 0),
        str(row.get("product_id") or ""),
    ))
    if scope == "trial":
        return rows[:10]
    return rows


def request_item_from_row(row: Mapping[str, Any]) -> Dict[str, Any]:
    tags = [str(tag).strip() for tag in row.get("final_subject_tags") or []]
    intro = str(row.get("final_intro") or "").strip()
    if len(tags) != 30:
        raise RuntimeError(f"{row.get('product_id')}: final tag count is not 30")
    if not intro:
        raise RuntimeError(f"{row.get('product_id')}: final intro is empty")
    attributes = [
        {"id": OZON_HASHTAG_ATTRIBUTE_ID, "values": [{"value": " ".join(tags)}]},
        {"id": OZON_ANNOTATION_ATTRIBUTE_ID, "values": [{"value": intro}]},
    ]
    if {attribute["id"] for attribute in attributes} != {OZON_HASHTAG_ATTRIBUTE_ID, OZON_ANNOTATION_ATTRIBUTE_ID}:
        raise RuntimeError("Unexpected attribute IDs in request")
    return {
        "product_id": int(row["product_id"]),
        "offer_id": str(row["offer_id"]),
        "attributes": attributes,
    }


def assert_no_preflight_drift(client: CountingOzonClient, rows: Sequence[Mapping[str, Any]]) -> None:
    offer_ids = [str(row.get("offer_id") or "") for row in rows]
    remote = {
        str(item.get("offer_id") or ""): dict(item)
        for item in product_attributes(client, offer_ids)
    }
    drifted: List[Dict[str, Any]] = []
    for row in rows:
        offer_id = str(row.get("offer_id") or "")
        item = remote.get(offer_id, {})
        actual_tags = split_tag_values(attribute_value_texts(item, OZON_HASHTAG_ATTRIBUTE_ID))
        actual_intro_values = attribute_value_texts(item, OZON_ANNOTATION_ATTRIBUTE_ID)
        actual_intro = actual_intro_values[0] if actual_intro_values else ""
        expected_current_tags = [str(tag) for tag in row.get("current_valid_subject_tags") or []]
        expected_current_intro = str(row.get("current_intro") or "")
        final_tags = [str(tag) for tag in row.get("final_subject_tags") or []]
        final_intro = str(row.get("final_intro") or "")
        current_matches = (
            [tag_key(tag) for tag in actual_tags if valid_existing_tag(tag)]
            == [tag_key(tag) for tag in expected_current_tags]
            and actual_intro == expected_current_intro
        )
        already_applied = (
            [tag_key(tag) for tag in actual_tags]
            == [tag_key(tag) for tag in final_tags]
            and actual_intro == final_intro
        )
        if not current_matches and not already_applied:
            drifted.append({
                "product_id": row.get("product_id"),
                "offer_id": offer_id,
                "expected_current_tag_count": len(expected_current_tags),
                "actual_tag_count": len(actual_tags),
                "expected_current_intro_sample": expected_current_intro[:300],
                "actual_intro_sample": actual_intro[:300],
            })
    if drifted:
        raise RuntimeError(f"Preflight drift detected before write: {json.dumps(drifted[:10], ensure_ascii=False)}")


def import_items(client: CountingOzonClient, task_id: int) -> List[Dict[str, Any]]:
    result = client.post(IMPORT_INFO_ENDPOINT, {"task_id": int(task_id)}).get("result") or {}
    return [dict(item) for item in result.get("items") or [] if isinstance(item, Mapping)]


def wait_for_task_group(client: CountingOzonClient, task_ids: Sequence[int], verify_seconds: int) -> List[Dict[str, Any]]:
    snapshots: List[Dict[str, Any]] = []
    started = time.monotonic()
    while True:
        elapsed = int(time.monotonic() - started)
        all_items: List[Dict[str, Any]] = []
        for task_id in task_ids:
            all_items.extend({"task_id": task_id, **item} for item in import_items(client, task_id))
        statuses = {
            status: sum(1 for item in all_items if str(item.get("status") or "") == status)
            for status in sorted({str(item.get("status") or "") for item in all_items})
        }
        errors = [
            {
                "task_id": item.get("task_id"),
                "product_id": str(item.get("product_id") or ""),
                "offer_id": str(item.get("offer_id") or ""),
                "status": str(item.get("status") or ""),
                "errors": [dict(error) for error in item.get("errors") or [] if isinstance(error, Mapping)],
            }
            for item in all_items
            if item.get("errors")
        ]
        snapshot = {
            "checked_at": now_iso(),
            "elapsed_seconds": elapsed,
            "item_count": len(all_items),
            "statuses": statuses,
            "error_item_count": len(errors),
            "error_items": errors,
        }
        snapshots.append(snapshot)
        print(json.dumps({
            "mode": "verifying",
            "task_ids": list(task_ids),
            "elapsed_seconds": elapsed,
            "statuses": statuses,
            "error_item_count": len(errors),
        }, ensure_ascii=False), flush=True)
        terminal = bool(all_items) and all(
            str(item.get("status") or "").casefold() in TERMINAL_IMPORT_STATUSES
            for item in all_items
        )
        if elapsed >= verify_seconds and terminal:
            break
        if elapsed >= max(verify_seconds, 300) and terminal:
            break
        if elapsed >= verify_seconds + 300:
            break
        time.sleep(min(30, max(1, verify_seconds - elapsed if elapsed < verify_seconds else 30)))
    return snapshots


def blocking_import_errors(items: Sequence[Mapping[str, Any]]) -> List[Dict[str, Any]]:
    blocking: List[Dict[str, Any]] = []
    for item in items:
        status = str(item.get("status") or "").casefold()
        raw_errors = [dict(error) for error in item.get("errors") or [] if isinstance(error, Mapping)]
        if status in {"failed", "skipped"}:
            blocking.append({
                "task_id": item.get("task_id"),
                "product_id": str(item.get("product_id") or ""),
                "offer_id": str(item.get("offer_id") or ""),
                "status": status,
                "errors": raw_errors,
            })
            continue
        for error in raw_errors:
            if str(error.get("level") or "").casefold() == "warning":
                continue
            attribute_id = str(error.get("attribute_id") or "")
            serialized = json.dumps(error, ensure_ascii=False).casefold()
            if attribute_id in TARGET_ATTRIBUTE_IDS or any(marker in serialized for marker in TARGET_ERROR_MARKERS):
                blocking.append({
                    "task_id": item.get("task_id"),
                    "product_id": str(item.get("product_id") or ""),
                    "offer_id": str(item.get("offer_id") or ""),
                    "status": status,
                    "errors": [error],
                })
    return blocking


def verify_readback(client: CountingOzonClient, rows: Sequence[Mapping[str, Any]]) -> Dict[str, Any]:
    offer_ids = [str(row.get("offer_id") or "") for row in rows]
    remote = {
        str(item.get("offer_id") or ""): dict(item)
        for item in product_attributes(client, offer_ids)
    }
    field_matches = 0
    field_mismatches: List[Dict[str, Any]] = []
    card_success = 0
    for row in rows:
        offer_id = str(row.get("offer_id") or "")
        item = remote.get(offer_id, {})
        actual_tags = split_tag_values(attribute_value_texts(item, OZON_HASHTAG_ATTRIBUTE_ID))
        expected_tags = [str(tag) for tag in row.get("final_subject_tags") or []]
        actual_intro_values = attribute_value_texts(item, OZON_ANNOTATION_ATTRIBUTE_ID)
        actual_intro = actual_intro_values[0] if actual_intro_values else ""
        expected_intro = str(row.get("final_intro") or "")
        tag_ok = [tag_key(tag) for tag in actual_tags] == [tag_key(tag) for tag in expected_tags]
        tag_shape_ok = (
            len(actual_tags) == 30
            and all(tag.startswith("#") and tag_body_length(tag) <= OZON_SUBJECT_TAG_MAX_BODY_LENGTH for tag in actual_tags)
        )
        intro_ok = actual_intro == expected_intro and actual_intro.startswith(str(row.get("base_intro") or ""))
        if tag_ok and tag_shape_ok:
            field_matches += 1
        else:
            field_mismatches.append({
                "product_id": row.get("product_id"),
                "offer_id": offer_id,
                "field": str(OZON_HASHTAG_ATTRIBUTE_ID),
                "expected": expected_tags,
                "actual": actual_tags,
                "tag_ok": tag_ok,
                "tag_shape_ok": tag_shape_ok,
            })
        if intro_ok:
            field_matches += 1
        else:
            field_mismatches.append({
                "product_id": row.get("product_id"),
                "offer_id": offer_id,
                "field": str(OZON_ANNOTATION_ATTRIBUTE_ID),
                "expected_prefix": str(row.get("base_intro") or "")[:300],
                "actual": actual_intro[:1000],
            })
        if tag_ok and tag_shape_ok and intro_ok:
            card_success += 1
    return {
        "card_success_count": card_success,
        "field_readback_match_count": field_matches,
        "field_readback_mismatch_count": len(field_mismatches),
        "field_readback_mismatches": field_mismatches,
    }


def apply_rows(
    client: CountingOzonClient,
    preflight_path: Path,
    preflight: Mapping[str, Any],
    *,
    scope: str,
    batch_size: int,
    verify_seconds: int,
    min_coverage: float = 0.95,
) -> Dict[str, Any]:
    conflict = active_write_conflicts()
    if conflict["active"]:
        raise RuntimeError("Active production write conflict: " + "; ".join(conflict["reasons"]))
    coverage = float((preflight.get("summary") or {}).get("coverage_ratio") or 0)
    if scope == "all" and coverage < min_coverage:
        raise RuntimeError(f"Preflight ready/already-ok coverage is below {min_coverage:.2%}: {coverage:.2%}")
    rows = selected_apply_rows(preflight, scope)
    if scope == "trial" and len(rows) != 10:
        raise RuntimeError(f"Trial requires exactly 10 ready update cards, found {len(rows)}")
    if not rows:
        raise RuntimeError("No ready rows require update")
    assert_no_preflight_drift(client, rows)

    receipt: Dict[str, Any] = {
        "schema_version": "1.0.0",
        "status": "running",
        "shop_id": SHOP_ID,
        "scope": scope,
        "started_at": now_iso(),
        "preflight_report": project_relative(preflight_path),
        "submitted_card_count": 0,
        "task_ids": [],
        "chunk_receipts": [],
        "items": rows,
        "write_api_calls": 0,
        "inventory_api_calls": 0,
    }
    receipt_path = save_report(f"{SHOP_ID}-{scope}-receipt", receipt)

    processed: List[Dict[str, Any]] = []
    for group in chunks(rows, max(1, min(batch_size, 100))):
        request_items = [request_item_from_row(row) for row in group]
        response = client.post(PRODUCT_ATTRIBUTES_UPDATE_ENDPOINT, {"items": request_items})
        task_id = int(response.get("task_id") or (response.get("result") or {}).get("task_id") or 0)
        if task_id <= 0:
            raise RuntimeError("Ozon accepted an attributes update without a task_id")
        receipt["task_ids"].append(task_id)
        receipt["submitted_card_count"] += len(group)
        print(json.dumps({
            "mode": "submitted",
            "scope": scope,
            "task_id": task_id,
            "card_count": len(group),
            "write_api_calls": client.write_api_calls,
            "inventory_api_calls": client.inventory_api_calls,
        }, ensure_ascii=False), flush=True)
        snapshots = wait_for_task_group(client, [task_id], verify_seconds)
        verification = verify_readback(client, group)
        chunk = {
            "task_id": task_id,
            "submitted_card_count": len(group),
            "task_snapshots": snapshots,
            **verification,
        }
        final_snapshot_items = [
            item for snapshot in snapshots[-1:] for item in snapshot.get("error_items") or []
        ]
        chunk["blocking_import_errors"] = blocking_import_errors(final_snapshot_items)
        chunk["non_field_import_error_count"] = max(
            0,
            len(final_snapshot_items) - len(chunk["blocking_import_errors"]),
        )
        receipt["chunk_receipts"].append(chunk)
        processed.extend(dict(row) for row in group)
        if chunk["blocking_import_errors"] or verification["field_readback_mismatch_count"]:
            receipt["status"] = "needs_review_stopped"
            receipt["stopped_reason"] = "target_import_errors_or_field_mismatches"
            receipt["blocking_import_errors"] = chunk["blocking_import_errors"]
            break
        if scope == "trial":
            break

    total_fields = len(processed) * 2
    field_matches = sum(int(chunk["field_readback_match_count"]) for chunk in receipt["chunk_receipts"])
    field_mismatches = sum(int(chunk["field_readback_mismatch_count"]) for chunk in receipt["chunk_receipts"])
    success_cards = sum(int(chunk["card_success_count"]) for chunk in receipt["chunk_receipts"])
    blocking_errors = [
        error
        for chunk in receipt["chunk_receipts"]
        for error in chunk.get("blocking_import_errors") or []
    ]
    receipt.update({
        "status": (
            "verified"
            if not blocking_errors and field_mismatches == 0 and success_cards == len(processed)
            else "needs_review_stopped"
        ),
        "verified_at": now_iso(),
        "processed_card_count": len(processed),
        "card_success_count": success_cards,
        "field_readback_match_count": field_matches,
        "field_readback_mismatch_count": field_mismatches,
        "field_success_ratio": round(field_matches / total_fields, 4) if total_fields else 0,
        "blocking_import_error_count": len(blocking_errors),
        "blocking_import_errors": blocking_errors,
        "non_field_import_error_count": sum(
            int(chunk.get("non_field_import_error_count") or 0) for chunk in receipt["chunk_receipts"]
        ),
        "write_api_calls": client.write_api_calls,
        "read_api_calls": client.read_api_calls,
        "inventory_api_calls": client.inventory_api_calls,
        "untouched": ["title", "price", "images", "brand", "category", "sku", "stock", "warehouse", "activation"],
    })
    receipt_path.write_text(json.dumps(receipt, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    receipt["receipt_report"] = project_relative(receipt_path)
    receipt_path.write_text(json.dumps(receipt, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return receipt


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--preflight", action="store_true", help="read zhonglian1 and build backup/preflight reports")
    parser.add_argument("--apply", choices=("trial", "all"), help="apply a saved preflight")
    parser.add_argument("--preflight-report", default="", help="preflight report path for --apply")
    parser.add_argument("--confirm", default="", help="required apply confirmation")
    parser.add_argument("--batch-size", type=int, default=50)
    parser.add_argument("--verify-seconds", type=int, default=600)
    parser.add_argument("--min-coverage", type=float, default=0.95)
    args = parser.parse_args()

    if not args.preflight and not args.apply:
        parser.error("Use --preflight or --apply")
    client = CountingOzonClient(load_credentials(SHOP_ID))
    if args.preflight:
        backup, preflight = build_preflight(client)
        print(json.dumps({
            "mode": "preflight",
            "shop_id": SHOP_ID,
            "backup_cards": backup["backup_card_count"],
            "summary": preflight["summary"],
            "backup_report": preflight["backup_report"],
            "preflight_report": preflight["preflight_report"],
            "current_write_conflict": preflight["current_write_conflict"],
            "write_api_calls": 0,
            "read_api_calls": preflight["read_api_calls"],
            "inventory_api_calls": preflight["inventory_api_calls"],
        }, ensure_ascii=False))
        return 0

    if args.confirm != CONFIRMATION:
        raise RuntimeError(f"Explicit confirmation is required: {CONFIRMATION}")
    if args.verify_seconds < 300:
        raise RuntimeError("Delayed field verification must run for at least 300 seconds")
    if not args.preflight_report:
        raise RuntimeError("--preflight-report is required for apply")
    preflight_path, preflight = load_preflight(args.preflight_report)
    receipt = apply_rows(
        client,
        preflight_path,
        preflight,
        scope=str(args.apply),
        batch_size=args.batch_size,
        verify_seconds=args.verify_seconds,
        min_coverage=args.min_coverage,
    )
    print(json.dumps({
        "status": receipt["status"],
        "scope": receipt["scope"],
        "submitted_card_count": receipt["submitted_card_count"],
        "processed_card_count": receipt["processed_card_count"],
        "card_success_count": receipt["card_success_count"],
        "field_readback_match_count": receipt["field_readback_match_count"],
        "field_readback_mismatch_count": receipt["field_readback_mismatch_count"],
        "field_success_ratio": receipt["field_success_ratio"],
        "task_ids": receipt["task_ids"],
        "write_api_calls": receipt["write_api_calls"],
        "read_api_calls": receipt["read_api_calls"],
        "inventory_api_calls": receipt["inventory_api_calls"],
        "receipt_report": receipt["receipt_report"],
    }, ensure_ascii=False))
    return 0 if receipt["status"] == "verified" else 2


if __name__ == "__main__":
    raise SystemExit(main())
