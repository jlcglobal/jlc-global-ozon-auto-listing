def search_window(period_days: int = SEARCH_PERIOD_DAYS) -> Tuple[str, str]:
    date_to = datetime.now(timezone.utc) - timedelta(days=3)
    date_from = date_to - timedelta(days=max(1, int(period_days)))
    return (
        date_from.isoformat(timespec="seconds").replace("+00:00", "Z"),
        date_to.isoformat(timespec="seconds").replace("+00:00", "Z"),
    )


def query_rows_from_response(response: Mapping[str, Any], *, fallback_sku: str = "") -> List[Dict[str, Any]]:
    result = response.get("result") if isinstance(response.get("result"), Mapping) else {}
    raw_rows = response.get("queries") or response.get("items") or result.get("queries") or result.get("items") or []
    rows: List[Dict[str, Any]] = []
    for raw in raw_rows:
        if not isinstance(raw, Mapping):
            continue
        query = compact_text(raw.get("query") or raw.get("name") or raw.get("query_ru"))
        if not query or not CYRILLIC_RE.search(query):
            continue
        count = _number(
            raw.get("unique_search_users")
            or raw.get("search_users")
            or raw.get("search_count")
            or raw.get("count")
            or raw.get("searches")
            or raw.get("impressions")
        )
        if count <= 0:
            continue
        row = dict(raw)
        row["query"] = query
        row["sku"] = str(raw.get("sku") or fallback_sku or "").strip()
        row["count"] = count
        row["value_score"] = _number(raw.get("value_score")) or round(count * 0.05, 3)
        row["source_kind"] = API_QUERY_SOURCE
        rows.append(row)
    rows.sort(key=lambda row: (_number(row.get("count")), _number(row.get("value_score"))), reverse=True)
    return rows


def product_query_details(
    client: CountingOzonClient,
    skus: Sequence[str],
    *,
    date_from: str,
    date_to: str,
) -> Tuple[Dict[str, List[Dict[str, Any]]], List[Dict[str, Any]]]:
    by_sku: Dict[str, List[Dict[str, Any]]] = {}
    errors: List[Dict[str, Any]] = []
    sku_values = sorted({str(sku).strip() for sku in skus if str(sku).strip().isdigit()})
    # Ozon validates limit_by_sku <= 15 and page_size <= 100. With six SKUs,
    # one response can contain the full top-15 set for each SKU.
    for group in chunks(sku_values, 6):
        try:
            response = client.post(PRODUCT_QUERY_DETAILS_ENDPOINT, {
                "date_from": date_from,
                "date_to": date_to,
                "limit_by_sku": 15,
                "page": 0,
                "page_size": 100,
                "skus": group,
                "sort_by": "BY_SEARCHES",
                "sort_dir": "DESCENDING",
            })
        except Exception as exc:
            errors.append({
                "sku_count": len(group),
                "skus": group,
                "error_type": type(exc).__name__,
                "error": str(exc)[:500],
            })
            continue
        fallback_sku = group[0] if len(group) == 1 else ""
        for row in query_rows_from_response(response, fallback_sku=fallback_sku):
            sku = str(row.get("sku") or "").strip()
            if not sku:
                continue
            target = by_sku.setdefault(sku, [])
            if len(target) < 15:
                target.append(row)
    return by_sku, errors


def attribute_value_texts(item: Mapping[str, Any], attribute_id: int) -> List[str]:
    values: List[str] = []
    for attribute in item.get("attributes") or []:
        if not isinstance(attribute, Mapping):
            continue
        current_id = str(attribute.get("id") or attribute.get("attribute_id") or "")
        if current_id != str(attribute_id):
            continue
        for raw in attribute.get("values") or []:
            if isinstance(raw, Mapping):
                text = raw.get("value") or raw.get("name") or raw.get("text")
            else:
                text = raw
            if str(text or "").strip():
                values.append(str(text).strip())
    return values


def tag_key(value: Any) -> str:
    return re.sub(r"[\s_#-]+", "", str(value or "").strip().casefold())


def tag_body_length(value: Any) -> int:
    return len(str(value or "").strip().lstrip("#"))


def split_tag_values(values: Sequence[Any]) -> List[str]:
    tags: List[str] = []
    seen: set[str] = set()
    for value in values:
        for token in TAG_SPLIT_RE.split(str(value or "")):
            tag = token.strip()
            if not tag:
                continue
            if not tag.startswith("#"):
                tag = "#" + tag.lstrip("#")
            key = tag_key(tag)
            if not key or key in seen:
                continue
            seen.add(key)
            tags.append(tag)
    return tags


def valid_existing_tag(tag: Any) -> bool:
    text = str(tag or "").strip()
    if not text.startswith("#") or re.search(r"\s", text):
        return False
    if not 0 < tag_body_length(text) <= OZON_SUBJECT_TAG_MAX_BODY_LENGTH:
        return False
    if _tag_policy_block_reason(text):
        return False
    if tag_key(text) in WEAK_CANDIDATE_TAG_BODIES:
        return False
    return True


def phrase_is_safe_for_tag(phrase: Any) -> bool:
    tokens = text_tokens(phrase)
    if not tokens:
        return False
    if any(token in STOPWORDS for token in tokens):
        return False
    if any(
        token == prefix or token.startswith(prefix)
        for token in tokens
        for prefix in BAD_FRAGMENT_TOKEN_PREFIXES
    ):
        return False
    if len(tokens) == 1 and tokens[0].endswith(ADJECTIVE_SINGLE_ENDINGS):
        return False
    return True


def add_unique_tag(target: List[Dict[str, Any]], tag: str, *, source: str, phrase: str) -> None:
    if not tag or not valid_existing_tag(tag):
        return
    if source in {"title", "intro_short_phrase", "attribute_short_phrase"} and not phrase_is_safe_for_tag(phrase):
        return
    key = tag_key(tag)
    if not key or key in WEAK_CANDIDATE_TAG_BODIES or key in {tag_key(item["tag"]) for item in target}:
        return
    target.append({"tag": tag, "source": source, "phrase": phrase})


def candidate_has_fragment(tag_body: str, phrase: str, fragments: Sequence[str]) -> bool:
    return any(fragment in tag_body or fragment in phrase for fragment in fragments)


