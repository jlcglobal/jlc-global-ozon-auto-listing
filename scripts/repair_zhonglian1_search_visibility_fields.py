def filter_card_candidates(candidates: Sequence[Mapping[str, Any]], card: Mapping[str, Any]) -> List[Dict[str, Any]]:
    result: List[Dict[str, Any]] = []
    seen: set[str] = set()
    for item in candidates:
        tag = str(item.get("tag") or "").strip()
        key = tag_key(tag)
        if not tag or not key or key in seen:
            continue
        if not candidate_allowed_for_card(item, card):
            continue
        seen.add(key)
        result.append(dict(item))
    return result


def compact_text(value: Any) -> str:
    return SPACE_RE.sub(" ", str(value or "")).strip()


def clean_original_candidate(value: Any) -> str:
    text = str(value or "").strip()
    if not text:
        return ""
    stripped = ADDED_SEARCH_SENTENCE_RE.sub("", text).strip()
    return stripped


def historical_original_evidence() -> Dict[str, Dict[str, Any]]:
    candidates: Dict[str, List[Dict[str, Any]]] = {}

    def remember(product_id: str, intro: str, *, source_type: str, path: Path, evidence_at: Any, rank: int) -> None:
        product_id = str(product_id or "").strip()
        intro = str(intro or "").strip()
        if not product_id or not intro:
            return
        if ADDED_SEARCH_SENTENCE_RE.search(intro):
            intro = clean_original_candidate(intro)
        if not intro:
            return
        candidates.setdefault(product_id, []).append({
            "intro": intro,
            "source_type": source_type,
            "source_report": project_relative(path),
            "evidence_at": str(evidence_at or ""),
            "source_rank": rank,
        })

    for path in sorted(RESTORE_DIR.glob("*-description-restore-preflight.json")):
        payload = load_json(path)
        evidence_at = payload.get("generated_at") or payload.get("applied_at")
        for item in payload.get("items") or []:
            if not isinstance(item, Mapping):
                continue
            remember(
                str(item.get("product_id") or ""),
                str(item.get("original_intro") or ""),
                source_type="restore_preflight_original_intro",
                path=path,
                evidence_at=evidence_at,
                rank=0,
            )

    for path in sorted(UPLOAD_DIR.glob("*.json")):
        payload = load_json(path)
        if str(payload.get("shop_id") or "") != SHOP_ID:
            continue
        evidence_at = payload.get("applied_at") or payload.get("submitted_at")
        for item in payload.get("request") or []:
            if not isinstance(item, Mapping):
                continue
            product_id = str(item.get("product_id") or "")
            for attribute in item.get("attributes") or []:
                if not isinstance(attribute, Mapping):
                    continue
                if str(attribute.get("id") or attribute.get("attribute_id") or "") != str(OZON_ANNOTATION_ATTRIBUTE_ID):
                    continue
                values = attribute.get("values") or []
                if not values:
                    continue
                raw_value = values[0].get("value") if isinstance(values[0], Mapping) else values[0]
                stripped = clean_original_candidate(raw_value)
                if stripped and stripped != str(raw_value or "").strip():
                    remember(
                        product_id,
                        stripped,
                        source_type="upload_request_stripped_intro",
                        path=path,
                        evidence_at=evidence_at,
                        rank=1,
                    )

    for path in sorted(REPAIR_DIR.glob("*-remaining-description-repair-*.json")):
        payload = load_json(path)
        if str(payload.get("shop_id") or "") != SHOP_ID:
            continue
        evidence_at = payload.get("generated_at") or payload.get("verified_at")
        for item in payload.get("items") or []:
            if not isinstance(item, Mapping):
                continue
            restored = str(item.get("restored_original_intro") or "").strip()
            current = str(item.get("current_intro") or "").strip()
            strategy = str(item.get("integration_strategy") or "")
            if strategy.startswith("manual_") and restored == current:
                continue
            if restored:
                remember(
                    str(item.get("product_id") or ""),
                    restored,
                    source_type="repair_report_restored_original_intro",
                    path=path,
                    evidence_at=evidence_at,
                    rank=2,
                )

    selected: Dict[str, Dict[str, Any]] = {}
    for product_id, rows in candidates.items():
        rows.sort(key=lambda row: (
            parse_time(row.get("evidence_at")) or 9_999_999_999.0,
            int(row.get("source_rank") or 99),
            row.get("source_report") or "",
        ))
        selected[product_id] = rows[0]
    return selected


def action_query_rows(action: Mapping[str, Any]) -> List[Dict[str, Any]]:
    evidence = action.get("evidence") if isinstance(action.get("evidence"), Mapping) else {}
    rows: List[Dict[str, Any]] = []
    for source_key, source_label in (
        ("top_queries", "ozon_search_analytics"),
        ("top_yandex_wordstat", "yandex_wordstat"),
    ):
        for raw in evidence.get(source_key) or []:
            if not isinstance(raw, Mapping):
                continue
            query = compact_text(raw.get("query") or raw.get("phrase") or raw.get("keyword"))
            if not query or not CYRILLIC_RE.search(query):
                continue
            row = dict(raw)
            metrics = row.get("metrics") if isinstance(row.get("metrics"), Mapping) else {}
            count = _query_search_count(row)
            if count <= 0:
                count = _number(metrics.get("impressions") or metrics.get("search_count") or row.get("count"))
            if count <= 0:
                continue
            row["query"] = query
            row["count"] = count
            row["value_score"] = _number(row.get("value_score")) or round(count * 0.05, 3)
            row["source_kind"] = source_label
            rows.append(row)
    rows.sort(key=lambda row: (_number(row.get("count")), _number(row.get("value_score"))), reverse=True)
    return rows


def text_tokens(value: Any) -> List[str]:
    return [token.casefold().replace("ё", "е") for token in TOKEN_RE.findall(str(value or ""))]


def stem(token: str) -> str:
    if token.isdigit() or len(token) <= 5:
        return token
    return token[:5]


def attribute_corpus(
    card: Mapping[str, Any],
    *,
    include_rich_text: bool = True,
    max_text_length: int = 5000,
) -> str:
    values: List[str] = []

    def iter_visible_text(value: Any) -> Iterable[str]:
        if value is None:
            return
        if isinstance(value, Mapping):
            for key, nested in value.items():
                if str(key).casefold() in {"src", "srcmobile", "imglink", "url", "href"}:
                    continue
                yield from iter_visible_text(nested)
            return
        if isinstance(value, Sequence) and not isinstance(value, (str, bytes, bytearray)):
            for nested in value:
                yield from iter_visible_text(nested)
            return
        text = str(value or "").strip()
        if not text:
            return
        if text.startswith("{") or text.startswith("["):
            if not include_rich_text:
                return
            try:
                parsed = json.loads(text)
            except json.JSONDecodeError:
                parsed = None
            if parsed is not None:
                yield from iter_visible_text(parsed)
                return
        if CYRILLIC_RE.search(text) and len(text) <= max_text_length:
            yield compact_text(text)

    for attribute in card.get("product_attributes") or []:
        if not isinstance(attribute, Mapping):
            continue
        attribute_id = str(attribute.get("id") or attribute.get("attribute_id") or "")
        if attribute_id in SKIP_ATTRIBUTE_IDS:
            continue
        for value in attribute.get("values") or []:
            for text in iter_visible_text(value):
                values.append(text)
    return " ".join(values)


def tag_fact_corpus(card: Mapping[str, Any]) -> str:
    return attribute_corpus(card, include_rich_text=False, max_text_length=90)


def query_supported(query: str, card: Mapping[str, Any], base_intro: str) -> bool:
    visible = compact_text(
        f"{card.get('title') or ''} {base_intro} {attribute_corpus(card, include_rich_text=True)}"
    ).casefold().replace("ё", "е")
    query_text = compact_text(query).casefold().replace("ё", "е")
    if not visible or not query_text:
        return False
    if query_text in visible:
        return True
    query_tokens = [token for token in text_tokens(query_text) if token not in STOPWORDS and len(token) > 2]
    if not query_tokens:
        return False
    visible_tokens = text_tokens(visible)
    visible_stems = {stem(token) for token in visible_tokens}
    if any(token.isdigit() and token not in visible_tokens for token in query_tokens):
        return False
    return all(stem(token) in visible_stems for token in query_tokens)


def safe_query(query: Any) -> str:
    text = compact_text(query).casefold()
    if not text or not CYRILLIC_RE.search(text):
        return ""
    if _query_policy_block_reason(text):
        return ""
    all_tokens = text_tokens(text)
    if not all_tokens:
        return ""
    if all_tokens[0] in STOPWORDS or all_tokens[-1] in STOPWORDS:
        return ""
    if len([token for token in all_tokens if token not in STOPWORDS]) < 1:
        return ""
    return text


def phrase_candidates_from_text(text: str, *, max_window: int = 3, include_single: bool = True) -> List[str]:
    tokens = [token for token in text_tokens(text) if token not in STOPWORDS and len(token) > 2]
    phrases: List[str] = []

    def add(value: str) -> None:
        value = compact_text(value)
        if value and value not in phrases:
            phrases.append(value)

    for size in tuple(range(max_window, 1, -1)):
        for index in range(0, max(0, len(tokens) - size + 1)):
            phrase = " ".join(tokens[index:index + size])
            if phrase_is_safe_for_tag(phrase):
                add(phrase)
    if include_single:
        for token in tokens:
            if phrase_is_safe_for_tag(token):
                add(token)
    return phrases


def has_token_prefix(tokens: Sequence[str], *prefixes: str) -> bool:
    return any(
        token == prefix or token.startswith(prefix)
        for token in tokens
        for prefix in prefixes
    )


